export interface ContactInfo {
  fullName: string;
  email: string;
  phone: string;
  location: string;
  links: string[];
}

export interface ExperienceEntry {
  id: string;
  title: string;
  company: string;
  location: string;
  startDate: string;
  endDate: string;
  bullets: string[];
  /** "Technologies: Swift • Kotlin …" listed under this job (FlowCV and many consultant resumes). */
  technologies?: string[];
}

export interface EducationEntry {
  id: string;
  degree: string;
  institution: string;
  date: string;
  details: string[];
  location?: string;
}

export interface ProjectEntry {
  id: string;
  name: string;
  description: string;
  bullets: string[];
}

export interface ParsedResume {
  contact: ContactInfo;
  headline: string;
  summary: string;
  skills: string[];
  experience: ExperienceEntry[];
  education: EducationEntry[];
  certifications: string[];
  projects: ProjectEntry[];
  publications: string[];
  languages: string[];
  links: string[];
  /** Lines the parser could not place — kept so nothing the user wrote is silently dropped. */
  unparsed: string[];
}

export type FactStatus = 'confirmed' | 'needs_review' | 'do_not_use';

export type FactKind = 'skill' | 'experience' | 'education' | 'certification' | 'project' | 'achievement' | 'other';

/** A single claim from the resume or profile that the AI may (or may not) use. */
export interface VerifiedFact {
  id: string;
  kind: FactKind;
  text: string;
  status: FactStatus;
  source: 'resume' | 'profile' | 'user';
}

/** One real job as the user typed it in the resume form. */
export interface BuilderJob {
  id: string;
  company: string;
  title: string;
  /** "Denver, CO" */
  city: string;
  /** "YYYY-MM" (month input). */
  start: string;
  /** "YYYY-MM", or empty when `current`. */
  end: string;
  current: boolean;
  /** What you did there — one accomplishment per line, in your own words. These become the bullets. */
  did: string;
  /** Tools and technologies you used in this job, comma-separated. */
  technologies: string;
}

export interface BuilderEducation {
  id: string;
  degree: string;
  field: string;
  school: string;
  city: string;
  start: string;
  end: string;
  /** Honors, GPA, thesis, relevant coursework — one per line (optional). */
  details?: string;
}

/** A resume entered in ApplyFlow's form instead of uploaded — every line is the user's own. */
export interface BuilderForm {
  /** Your usual title, e.g. "Senior Video Playback Engineer". */
  headline: string;
  /** Optional: a few sentences about yourself, in your own words. */
  summary: string;
  skills: string;
  certifications: string;
  languages: string;
  jobs: BuilderJob[];
  education: BuilderEducation[];
}

export interface MasterResume {
  id: string;
  name: string;
  isDefault: boolean;
  rawText: string;
  parsed: ParsedResume;
  facts: VerifiedFact[];
  sourceFileName: string | null;
  sourceFormat: 'docx' | 'pdf' | 'text' | 'form';
  /** Set when the resume was entered in ApplyFlow's form (edited there, never re-read from text). */
  builder?: BuilderForm | null;
  /** Version of the resume reader that produced `parsed`; older resumes are re-read automatically. */
  parserVersion?: number;
  /** The original uploaded file, kept so a better reader can re-read it later. Never sent anywhere. */
  sourceData?: ArrayBuffer | null;
  createdAt: string;
  updatedAt: string;
}

export type SensitiveCategory =
  | 'sponsorship'
  | 'work_authorization'
  | 'security_clearance'
  | 'criminal_background'
  | 'disability'
  | 'veteran'
  | 'demographic'
  | 'salary'
  | 'relocation'
  | 'years_experience'
  | 'legal_consent'
  | 'date_of_birth';

/** An answer the user wrote and explicitly approved for reuse. Never generated by AI. */
export interface ApprovedAnswer {
  id: string;
  category: SensitiveCategory | 'general';
  /** Question text or keywords this answer applies to. */
  questionPattern: string;
  answer: string;
  approvedAt: string;
  /** Last time this answer was auto-filled on an application. */
  lastUsedAt?: string;
  /** How many times this answer was reused. */
  useCount?: number;
}

export interface CareerProfile {
  fullName: string;
  email: string;
  phone: string;
  location: string;
  headline: string;
  professionalSummary: string;
  verifiedSkills: string[];
  /** Stored for the user's reference only; never auto-submitted to forms. */
  workAuthorizationNote: string;
  preferredTitles: string[];
  preferredLocations: string[];
  remotePreference: 'remote' | 'hybrid' | 'onsite' | 'any';
  salaryPreference: string;
  availability: string;
  portfolioLinks: string[];
  linkedinUrl: string;
  githubUrl: string;
  approvedAnswers: ApprovedAnswer[];
  updatedAt: string;
}
